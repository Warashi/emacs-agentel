def ranges(path):
    section = None
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("## "):
                section = line[3:].strip()
            elif section == "CJK characters":
                match = re.match(r"- U\+([0-9A-F]+)(?:\.\.U\+([0-9A-F]+))?", line)
                if match:
                    yield int(match.group(1), 16), int(match.group(2) or match.group(1), 16)


def main():
    print(HEADER, end="")
    for start, end in ranges(sys.argv[1]):
        print(f"                     (#x{start:X} . #x{end:X})")
    print(FOOTER, end="")


if __name__ == "__main__":
    main()
